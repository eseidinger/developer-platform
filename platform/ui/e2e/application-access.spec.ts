import { expect, test } from '@playwright/test'
import { accessFixture } from './access-fixture.ts'

test('defines governance, groups and a reviewed policy, then waits for activation', async ({ page }) => {
  const fixture = await accessFixture(page, { withPolicy: false })
  await page.goto('/e2e/access-harness.html?view=governance')
  await page.getByRole('button', { name: 'Edit governance' }).click()
  await page.getByLabel('Domain retention owner').fill('Application owner')
  await page.getByLabel('Domain retention policy').fill('Delete domain rows after 30 days')
  await page.getByLabel('Purge authority').fill('Project owner')
  await page.getByLabel('Recovery owner').fill('Operations')
  await page.getByRole('button', { name: 'Save governance' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: 'Groups', exact: true }).click()
  await page.getByRole('button', { name: 'Create application group' }).click()
  await page.getByLabel('Group name', { exact: true }).fill('admins')
  await page.getByLabel('Display name', { exact: true }).fill('Application administrators')
  await page.getByRole('button', { name: 'Create group', exact: true }).click()
  await expect(page.getByText('Application administrators (admins)', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Policy', exact: true }).click()
  await page.getByRole('button', { name: 'Define access policy' }).click()
  await expect(page.getByRole('button', { name: 'Save policy' })).toBeDisabled()
  await expect(page.getByLabel('Release email to the application')).toBeDisabled()
  await page.getByLabel('Rule 1 name', { exact: true }).fill('interactive')
  await page.getByLabel('Rule 1 path', { exact: true }).fill('/app/')
  await page.getByRole('checkbox', { name: 'Readers (readers)' }).check()
  await page.getByRole('button', { name: 'Add route rule' }).click()
  await page.getByLabel('Rule 2 name', { exact: true }).fill('machine')
  await page.getByLabel('Rule 2 path', { exact: true }).fill('/api/')
  await page.getByLabel('Rule 2 authentication').selectOption('bearer-token')
  await page.getByRole('group', { name: 'Rule 2 groups' }).getByRole('checkbox', { name: 'Readers (readers)' }).check()
  await page.getByRole('button', { name: 'Review policy' }).click()
  await expect(page.getByText('Permitted routes', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save policy' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText('active', { exact: true }).first()).toBeVisible({ timeout: 10_000 })
  const write = fixture.mutations.find((m) => m.path.endsWith('/access-policy'))
  expect(write?.headers['if-match']).toBe('"0"')
  expect(JSON.stringify(write?.body)).not.toMatch(/clientSecret|audience|redirectUri/)
  expect(fixture.getPolicy()?.state).toBe('active')
})

