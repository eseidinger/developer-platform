test('provider approval and consumer rotation/adoption/revocation show metadata only', async ({ page }) => {
  const fixture = await accessFixture(page)
  await page.goto('/e2e/access-harness.html?view=services')
  await page.getByRole('button', { name: 'Approve service', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approve service request' })).toBeDisabled()
  await page.getByRole('checkbox', { name: 'Readers (readers)' }).check()
  await page.getByRole('button', { name: 'Approve service request' }).click()
  await expect(page.getByText('active', { exact: true }).first()).toBeVisible({ timeout: 10_000 })
  await page.goto('/e2e/access-harness.html?project=consumer&view=services')
  await expect(page.getByText('ACCESS_FIXTURE_CLIENT_SECRET', { exact: true })).toBeVisible()
  await expect(page.getByText('MUST-NOT-RENDER')).toHaveCount(0)
  await page.getByRole('button', { name: 'Rotate credential' }).click()
  await page.getByRole('button', { name: 'Rotate service credential' }).click()
  await expect(page.getByRole('button', { name: 'Confirm adoption' })).toBeVisible({ timeout: 10_000 })
  await page.getByRole('button', { name: 'Confirm adoption' }).click()
  await page.getByRole('button', { name: 'Confirm credential adoption' }).click()
  await expect(page.getByText('Adoption: confirmed')).toBeVisible()
  await page.getByRole('button', { name: 'Emergency rotation', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('no overlap')
  await page.getByRole('dialog').getByRole('button', { name: 'Emergency rotation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Rotate credential' })).toBeVisible({ timeout: 10_000 })
  expect(fixture.mutations.filter((m) => m.path.endsWith('/rotate')).at(-1)?.body).toEqual({ emergency: true })
  await page.getByRole('button', { name: 'Revoke service', exact: true }).click()
  await page.getByRole('button', { name: 'Revoke service access' }).click()
  await expect(page.getByText('revoked', { exact: true }).first()).toBeVisible({ timeout: 10_000 })
  expect(fixture.services[0]?.state).toBe('revoked')
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(storage).toBe('{"local":{},"session":{}}')
})

