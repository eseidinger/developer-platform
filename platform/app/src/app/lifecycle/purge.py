"""Erase live resources, then require verified removal from operational storage."""

from fastapi import HTTPException
from psycopg import sql
from psycopg.types.json import Jsonb

from .. import access_store
from ..stores import catalog as stores
from ..stores import providers


def purge_stores(conn, project):
    rows = conn.execute(
        """SELECT row_to_json(r) FROM store_resources r WHERE owner_project=%s ORDER BY resource_id""",
        (project,),
    ).fetchall()
    for (resource,) in rows:
        live = conn.execute(
            """SELECT 1 FROM store_credentials c JOIN store_grants g USING(grant_id)
            WHERE g.resource_id=%s AND c.state<>'revoked' LIMIT 1""",
            (resource["resource_id"],),
        ).fetchone()
        if live:
            return False
        if resource["state"] != "purged":
            providers.get(resource["provider"]).purge(resource)
            conn.execute(
                "UPDATE store_resources SET state='purged',observed_state='purged' WHERE resource_id=%s",
                (resource["resource_id"],),
            )
    return True


def delete_catalog(conn, control, project, project_id, operation_id):
    # Capture every associated grant before deleting references. The IDs are
    # generated by the platform; dynamic SQL below uses only fixed table names.
    grants = [
        r[0]
        for r in conn.execute(
            """SELECT g.grant_id FROM store_grants g JOIN store_resources r USING(resource_id)
        WHERE r.owner_project=%s OR g.consumer_project=%s""",
            (project, project),
        ).fetchall()
    ]
    credentials = [
        r[0]
        for r in conn.execute(
            "SELECT credential_id FROM store_credentials WHERE grant_id=ANY(%s::uuid[])",
            (grants,),
        ).fetchall()
    ]
    audit_ids = [str(value) for value in grants + credentials]
    for query in (
        "SELECT resource_id::text FROM store_resources WHERE owner_project=%s",
        "SELECT credential_id::text FROM deployment_credentials WHERE project=%s",
        "SELECT run_id::text FROM ai_runs WHERE project=%s",
        "SELECT proposal_id::text FROM ai_change_proposals WHERE project=%s",
    ):
        audit_ids.extend(row[0] for row in conn.execute(query, (project,)).fetchall())
    machines = conn.execute(
        "SELECT issuer,subject FROM deployment_credentials WHERE project=%s", (project,)
    ).fetchall()
    # PostgreSQL login tombstones are useful during normal rotation but are part
    # of a complete purge. Revocation has already removed their permissions.
    for row in conn.execute(
        """SELECT c.credential_id FROM store_credentials c JOIN store_grants g USING(grant_id)
        JOIN store_resources r USING(resource_id) WHERE g.grant_id=ANY(%s::uuid[]) AND r.provider='postgresql'""",
        (grants,),
    ).fetchall():
        role = stores.login(row[0])
        conn.execute(sql.SQL("DROP ROLE IF EXISTS {}").format(sql.Identifier(role)))
    conn.execute(
        "DELETE FROM store_console_sessions WHERE credential_id=ANY(%s::uuid[])",
        (credentials,),
    )
    conn.execute(
        "UPDATE store_grants SET delivered_credential_id=NULL WHERE grant_id=ANY(%s::uuid[])",
        (grants,),
    )
    conn.execute(
        "DELETE FROM store_credentials WHERE grant_id=ANY(%s::uuid[])", (grants,)
    )
    conn.execute("DELETE FROM store_grants WHERE grant_id=ANY(%s::uuid[])", (grants,))
    conn.execute(
        "DELETE FROM store_instances WHERE resource_id IN (SELECT resource_id FROM store_resources WHERE owner_project=%s)",
        (project,),
    )
    conn.execute("DELETE FROM store_resources WHERE owner_project=%s", (project,))
    conn.execute("DELETE FROM store_project_retirements WHERE project=%s", (project,))
    # Incoming revoked service relationships also carry the provider's project
    # name and must not remain as dangling history in a surviving consumer.
    hosted_ids = [
        row["id"]
        for row in access_store.listing(conn)
        if row["project"] == project or row["spec"].get("providerProject") == project
    ]
    conn.execute(
        "DELETE FROM hosted_access_idempotency WHERE resource_id=ANY(%s::text[])",
        (hosted_ids,),
    )
    conn.execute(
        "DELETE FROM hosted_access_operations WHERE resource_id=ANY(%s::text[])",
        (hosted_ids,),
    )
    audit_ids.extend(hosted_ids)
    principal_ids = [
        r[0]
        for r in conn.execute(
            "SELECT spec->>'principalId' FROM hosted_access_resources WHERE id=ANY(%s::text[])",
            (hosted_ids,),
        ).fetchall()
        if r[0]
    ]
    conn.execute(
        "DELETE FROM hosted_access_resources WHERE id=ANY(%s::text[])", (hosted_ids,)
    )
    conn.execute(
        "DELETE FROM hosted_access_principals WHERE id=ANY(%s::text[]) AND id NOT IN (SELECT spec->>'principalId' FROM hosted_access_resources WHERE spec ? 'principalId')",
        (principal_ids,),
    )
    # rotated_from is a self-reference with RESTRICT, so sever it first.
    conn.execute(
        "UPDATE deployment_credentials SET rotated_from=NULL WHERE project=%s",
        (project,),
    )
    conn.execute(
        "DELETE FROM project_recovery_points WHERE project_id=%s", (project_id,)
    )
    conn.execute(
        "DELETE FROM project_lifecycle_operations WHERE project_id=%s AND operation_id<>%s",
        (project_id, operation_id),
    )
    # Only the privileged catalog connection can perform this confirmed purge.
    # Transactional DDL holds a write lock while the append-only guard is paused;
    # ordinary writers remain blocked, and rollback also restores the guard.
    with conn.transaction():
        conn.execute(
            "ALTER TABLE platform_audit.events DISABLE TRIGGER events_append_only"
        )
        conn.execute(
            """DELETE FROM platform_audit.events WHERE scope->>'project'=%s OR
        target_id=ANY(%s::text[]) OR detail->>'grant_id'=ANY(%s::text[]) OR
        detail->>'consumer_project'=%s OR
        (target_kind='project' AND target_id=%s) OR operation_id IN
        (SELECT operation_id::text FROM application_operations WHERE application_id IN
        (SELECT a.application_id FROM project_applications a JOIN project_environments e USING(environment_id)
        WHERE e.project_id=%s))""",
            (project, audit_ids, audit_ids, project, project, project_id),
        )
        conn.execute(
            "ALTER TABLE platform_audit.events ENABLE TRIGGER events_append_only"
        )
    control.delete_project_catalog(conn, project)
    for issuer, subject in machines:
        conn.execute(
            "DELETE FROM platform_principals WHERE issuer=%s AND subject=%s AND NOT EXISTS(SELECT 1 FROM platform_grants WHERE issuer=%s AND subject=%s) AND NOT EXISTS(SELECT 1 FROM deployment_credentials WHERE issuer=%s AND subject=%s)",
            (issuer, subject, issuer, subject, issuer, subject),
        )
    # The original catalog helper retained ownership tombstones. All referenced
    # stores and grants above are now gone, so deleting the project is complete.
    conn.execute("DELETE FROM projects WHERE project_id=%s", (project_id,))


def purge(conn, control, operation):
    from .worker import retire

    step = operation["step"]
    if step == "prepare":
        if not retire(conn, control, operation):
            return False
        conn.execute(
            "UPDATE project_lifecycle_operations SET step='stores',updated_at=now() WHERE operation_id=%s",
            (operation["operation_id"],),
        )
        return False
    if step == "stores":
        conn.execute("SELECT pg_advisory_lock(731904)")
        try:
            complete = purge_stores(conn, operation["project"])
        finally:
            conn.execute("SELECT pg_advisory_unlock(731904)")
        if not complete:
            return False
        resource_ids = [
            row[0]
            for row in conn.execute(
                "SELECT resource_id::text FROM store_resources WHERE owner_project=%s",
                (operation["project"],),
            ).fetchall()
        ]
        conn.execute(
            "UPDATE project_lifecycle_operations SET step='external_erasure',result=result || %s,updated_at=now() WHERE operation_id=%s",
            (Jsonb({"store_resource_ids": resource_ids}), operation["operation_id"]),
        )
        return False
    if step == "external_erasure":
        from .erasure import request, verified_receipt

        request(operation)
        if not verified_receipt(operation):
            raise HTTPException(409, "Operational data and backup erasure is pending")
        with conn.transaction():
            conn.execute("SELECT pg_advisory_xact_lock(731904)")
            delete_catalog(
                conn,
                control,
                operation["project"],
                operation["project_id"],
                operation["operation_id"],
            )
            conn.execute(
                "UPDATE project_lifecycle_operations SET step='catalog_removed',result=%s WHERE operation_id=%s",
                (
                    Jsonb(
                        {
                            **operation["result"],
                            "live_resources_removed": True,
                            "operational_data_removed": True,
                            "backups_removed": False,
                        }
                    ),
                    operation["operation_id"],
                ),
            )
        # The maintenance runner must take a final clean backup after catalog
        # deletion and prune snapshots that predate it. Keep the name reserved
        # via the lifecycle ledger until its final receipt is available.
        return False
    return False
